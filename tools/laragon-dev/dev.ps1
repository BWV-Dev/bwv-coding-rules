function Get-InfisicalExe($Config) {
    $p = Get-Prop $Config 'infisicalPath'
    if ($p) { return $p }
    $c = Get-Command infisical -CommandType Application -All -ErrorAction SilentlyContinue |
        Where-Object { $_.Source -match '\.(exe|cmd|bat)$' } |
        Sort-Object { if ($_.Source -match '\.exe$') { 0 } else { 1 } } | Select-Object -First 1
    if (-not $c) { Fail 'Infisical CLI (infisical.exe / infisical.cmd) not found in PATH. You can set "infisicalPath" in projects.json' }
    $c.Source
}

function Get-InfisicalArgs($Settings) {
    $a = @()
    if ($Settings.ProjectId) { $a += @('--projectId', $Settings.ProjectId) }
    if ($Settings.Env) { $a += @('--env', $Settings.Env) }
    if ($Settings.Path) { $a += @('--path', $Settings.Path) }
    $a
}

# Run `infisical export` for many projects in parallel (at most $Throttle processes); stdout goes straight to memory.
# Returns a hashtable: project name -> secrets.
function Get-AllProjectSecrets($Projects, [string]$InfisicalExe, [int]$Throttle = 8) {
    $result = @{}
    $queue = [Collections.Generic.Queue[object]]::new([object[]]@($Projects))
    $running = [Collections.Generic.List[object]]::new()
    while ($queue.Count -or $running.Count) {
        while ($queue.Count -and $running.Count -lt $Throttle) {
            $p = $queue.Dequeue()
            $args_ = @('export', '--format', 'json', '--silent') + @(Get-InfisicalArgs $p.Settings)
            $running.Add([pscustomobject]@{ Project = $p; Handle = (Start-Captured $InfisicalExe $args_ $p.Dir) })
        }
        $done = @($running | Where-Object { $_.Handle.Process.HasExited })
        if (-not $done.Count) { Start-Sleep -Milliseconds 100; continue }
        foreach ($d in $done) {
            [void]$running.Remove($d)
            $result[$d.Project.Name] = ConvertFrom-SecretExport $d.Project (Wait-Captured $d.Handle)
        }
    }
    $result
}

function ConvertFrom-SecretExport($Project, $r) {
    if ($r.ExitCode -ne 0) {
        Fail "infisical export failed for '$($Project.Name)' (exit $($r.ExitCode)): $($r.StdErr.Trim())`n  → Did you run 'infisical login'? Are .infisical.yaml / projectId / env correct?"
    }
    # Windows PowerShell 5.1 emits a JSON array as one object; ForEach-Object unrolls it (no-op on PowerShell 7)
    try { $items = @(ConvertFrom-Json -InputObject $r.StdOut | ForEach-Object { $_ }) }
    catch { Fail "Could not parse JSON from infisical export for '$($Project.Name)'" }
    $secrets = [ordered]@{}
    if ($items.Count -gt 0 -and $items[0].PSObject.Properties['key']) {
        foreach ($s in $items) { $secrets[[string]$s.key] = [string]$s.value }
    } elseif ($items.Count -gt 0) {
        foreach ($p in $items[0].PSObject.Properties) { $secrets[$p.Name] = [string]$p.Value }
    }
    $secrets
}

function ConvertTo-EnvPrefix([string]$Name) { 'IDEV_' + ($Name.ToUpperInvariant() -replace '[^A-Z0-9]', '_') + '__' }

# Values live in the Apache process env (IDEV_<PROJECT>__KEY); the vhost only has `SetEnv KEY "${IDEV_<PROJECT>__KEY}"`.
# Apache substitutes ${...} while reading the config, before splitting arguments, so \ and " must be escaped
# and multi-line values are rejected.
function Build-SecretVars($Project, $Secrets, [string]$Prefix) {
    $vars = [ordered]@{}
    $lines = @()
    foreach ($key in @($Secrets.get_Keys())) {
        $value = [string]$Secrets[$key]
        if ($key -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { Write-Warn "$($Project.Name): skipped '$key' (invalid variable name)"; continue }
        if ($value -match "[`r`n]") { Write-Warn "$($Project.Name): skipped $key (multi-line values are not supported by SetEnv; consider storing it base64-encoded)"; continue }
        if ($value.Length -gt 16000) { Write-Warn "$($Project.Name): skipped $key (longer than 16000 characters)"; continue }
        $envName = $Prefix + $key
        # Inside a quoted argument Apache treats \\ and \" as escapes
        $vars[$envName] = $value.Replace('\', '\\').Replace('"', '\"')
        $lines += "    SetEnv $key `"`${$envName}`""
    }
    [pscustomobject]@{ Vars = $vars; Lines = $lines }
}

