$command = if ($args.Count) { [string]$args[0] } else { 'help' }
$rest = @($args | Select-Object -Skip 1)
$script:ExitCode = 0
try {
    switch ($command) {
        'up'           { Invoke-Up ($rest -contains '--no-hosts') }
        'restart'      { Invoke-Up ($rest -contains '--no-hosts') }
        'down'         { Stop-All }
        'status'       { Invoke-Status }
        'run'          { Invoke-Run $rest }
        'selftest'     { Invoke-SelfTest $rest }
        'hosts-reset'  { Update-Hosts $null $false }
        '_write-hosts' { Write-HostsFile ([IO.File]::ReadAllText($rest[0])) }
        default {
            $help = (Get-Content $PSCommandPath -Raw -Encoding UTF8) -split '#>' | Select-Object -First 1
            Write-Host ($help -replace '^<#\s*', '')
        }
    }
} catch {
    Write-Host "✗ $($_.Exception.Message)" -ForegroundColor Red
    exit 1
}
exit $script:ExitCode
