function Get-ProjectDir([string]$DocRoot, $Lg) {
    foreach ($www in $Lg.WwwRoots) {
        if ($DocRoot.StartsWith("$www\", [StringComparison]::OrdinalIgnoreCase)) {
            return Join-Path $www ($DocRoot.Substring($www.Length + 1).Split('\')[0])
        }
    }
    $null
}

function New-TplConf($Lg, [string]$Tpl, [string]$DocRoot, [string]$Site) {
    $sslDirWin = Split-Path $Lg.SslCrt -Parent
    $sslDir = ConvertTo-ApachePath $sslDirWin
    $text = $Tpl.Replace('<<PROJECT_DIR>>', (ConvertTo-ApachePath $DocRoot)).Replace('<<HOSTNAME>>', $Site).
        Replace('<<PORT>>', "$($Lg.Port)").Replace('<<SSL_PORT>>', "$($Lg.SslPort)").Replace('<<SSL_DIR>>', $sslDir)
    # Laragon uses one laragon.crt for every site
    if (-not (Test-Path (Join-Path $sslDirWin "$Site.crt"))) {
        $text = $text.Replace("$sslDir/$Site.crt", (ConvertTo-ApachePath $Lg.SslCrt)).Replace("$sslDir/$Site.key", (ConvertTo-ApachePath $Lg.SslKey))
    }
    $text
}

# A project = a Laragon auto.*.conf vhost; www folders without a vhost get one rendered from VirtualHost.tpl.
# Vhosts that don't follow Laragon's template (hand-written) are included as-is into the default PHP instance.
function Get-Projects($Lg, $Config) {
    $projects = [Collections.Generic.List[object]]::new()
    $extra = [Collections.Generic.List[string]]::new()
    $seen = @{}
    if (Test-Path $Lg.SitesDir) {
        foreach ($f in Get-ChildItem $Lg.SitesDir -Filter '*.conf' -File | Sort-Object Name) {
            if ($f.Name -ieq '00-default.conf') { continue }
            $text = [IO.File]::ReadAllText($f.FullName)
            $root = [regex]::Match($text, '(?im)^\s*define\s+ROOT\s+"([^"]+)"')
            $site = [regex]::Match($text, '(?im)^\s*define\s+SITE\s+"([^"]+)"')
            # Laragon 6 writes auto.*.conf without the defines
            if (-not ($root.Success -and $site.Success) -and $f.Name -like 'auto.*.conf') {
                $root = [regex]::Match($text, '(?im)^\s*DocumentRoot\s+"([^"]+)"')
                $site = [regex]::Match($text, '(?im)^\s*ServerName\s+"?([^"\s]+)')
            }
            $docRoot = if ($root.Success) { $root.Groups[1].Value.Replace('/', '\').TrimEnd('\') } else { $null }
            $dir = if ($docRoot) { Get-ProjectDir $docRoot $Lg } else { $null }
            if (-not ($site.Success -and $dir)) { $extra.Add($f.FullName); continue }
            if (-not (Test-Path $dir)) { continue }   # stale vhost of a deleted project
            $name = Split-Path $dir -Leaf
            if ($seen.ContainsKey($name)) { continue }
            $seen[$name] = $true
            $projects.Add([pscustomobject]@{ Name = $name; Site = $site.Groups[1].Value; DocRoot = $docRoot; Dir = $dir; ConfText = $text; Source = 'laragon' })
        }
    }
    $hostTpl = Get-Prop $Config 'hostnameTemplate'
    if (-not $hostTpl) { $hostTpl = '{name}.test' }
    $tpl = if (Test-Path $Lg.TplFile) { [IO.File]::ReadAllText($Lg.TplFile) } else { $null }
    if ($tpl) {
        foreach ($www in $Lg.WwwRoots) {
            foreach ($d in Get-ChildItem $www -Directory) {
                if ($seen.ContainsKey($d.Name) -or $d.Name.StartsWith('.')) { continue }
                $seen[$d.Name] = $true
                $site = $hostTpl.Replace('{name}', $d.Name.ToLowerInvariant())
                $public = Join-Path $d.FullName 'public'
                $docRoot = if (Test-Path $public -PathType Container) { $public } else { $d.FullName }
                $projects.Add([pscustomobject]@{ Name = $d.Name; Site = $site; DocRoot = $docRoot; Dir = $d.FullName; ConfText = (New-TplConf $Lg $tpl $docRoot $site); Source = 'tpl' })
            }
        }
    }
    [pscustomobject]@{ Projects = $projects; Extra = $extra }
}

function Get-ProjectSettings($Project, $Config) {
    $cfg = Get-Prop (Get-Prop $Config 'projects') $Project.Name
    $projectId = Get-Prop $cfg 'projectId'
    $hasConfig = @('.infisical.yaml', '.infisical.json') | Where-Object { Test-Path (Join-Path $Project.Dir $_) }
    $enabled = (Get-Prop $cfg 'infisical') -ne $false -and ($hasConfig -or $projectId)
    [pscustomobject]@{
        Php       = Get-Prop $cfg 'php'
        Infisical = [bool]$enabled
        ProjectId = $projectId
        Env       = Get-Prop $cfg 'env'
        Path      = Get-Prop $cfg 'path'
    }
}

