function Invoke-Up([bool]$NoHosts) {
    Stop-All -Quiet
    $lg = Get-Laragon
    $config = Get-Config
    $phpBuilds = @(Get-PhpBuilds $lg)
    $apacheBuilds = @(Get-ApacheBuilds $lg)
    $defaultPhp = Resolve-PhpBuild $null $phpBuilds $lg
    $disc = Get-Projects $lg $config
    Write-Step "Laragon $($lg.Root): Apache $($lg.ApacheVersion), default PHP $($defaultPhp.Version), $($disc.Projects.Count) project(s)"

    Write-CertWarning $disc.Projects $lg

    $instances = [ordered]@{}
    foreach ($p in $disc.Projects) {
        $s = Get-ProjectSettings $p $config
        $php = Resolve-PhpBuild $s.Php $phpBuilds $lg
        if (-not $instances.Contains($php.Name)) {
            $instances[$php.Name] = New-Instance $php ($php.Name -eq $defaultPhp.Name) (Resolve-Apache $php $config $apacheBuilds $lg)
        }
        $p | Add-Member -Force -NotePropertyName Settings -NotePropertyValue $s
        $instances[$php.Name].Projects.Add($p)
    }

    $withSecrets = @($disc.Projects | Where-Object { $_.Settings.Infisical })
    $secrets = @{}
    if ($withSecrets.Count) {
        $sw = [Diagnostics.Stopwatch]::StartNew()
        Write-Step "Fetching secrets from Infisical for $($withSecrets.Count) project(s)..."
        $secrets = Get-AllProjectSecrets $withSecrets (Get-InfisicalExe $config)
        Write-Host "  done in $([math]::Round($sw.Elapsed.TotalSeconds, 1))s"
    }

    $prefixes = @{}
    foreach ($inst in $instances.Values) {
        foreach ($p in $inst.Projects) {
            $lines = @()
            $count = 0
            if ($p.Settings.Infisical) {
                $base = ConvertTo-EnvPrefix $p.Name
                $prefix = $base
                for ($n = 2; $prefixes.ContainsKey($prefix); $n++) { $prefix = $base.TrimEnd('_') + "_$n" + '__' }
                $prefixes[$prefix] = $true
                $b = Build-SecretVars $p $secrets[$p.Name] $prefix
                foreach ($k in $b.Vars.Keys) { $inst.EnvVars[$k] = $b.Vars[$k] }
                $lines = $b.Lines
                $count = $b.Vars.Count
            }
            $p | Add-Member -Force -NotePropertyName SecretCount -NotePropertyValue $count
            $p | Add-Member -Force -NotePropertyName GeneratedConf -NotePropertyValue (New-ProjectConf $p $lines)
        }
    }
    if ($disc.Extra.Count) {
        if (-not $instances.Contains($defaultPhp.Name)) {
            $instances[$defaultPhp.Name] = New-Instance $defaultPhp $true (Resolve-Apache $defaultPhp $config $apacheBuilds $lg)
        }
        $instances[$defaultPhp.Name].ExtraConfs = $disc.Extra.ToArray()
    }

    Assert-PortsFree @($instances.Values) $lg
    Initialize-HealthFile
    $started = @()
    $failed = @()
    foreach ($inst in @($instances.Values)) {
        $order = @($inst.Apache) + @($apacheBuilds | Where-Object Name -ne $inst.Apache.Name)
        $r = $null
        foreach ($ap in $order) {
            $inst.Apache = $ap
            Write-InstanceFiles $inst $lg
            $r = Start-Instance $inst $lg
            if ($r.Ok) { break }
            Write-Warn "PHP $($inst.Php.Version) + $($ap.Name): $($r.Error)"
        }
        if (-not $r.Ok) { $failed += $inst; continue }
        $inst.Pid = $r.Pid
        $started += $inst
        if ($inst.Apache.Name -ne $order[0].Name) {
            Write-Warn "PHP $($inst.Php.Version) runs on $($inst.Apache.Name). Pin it in projects.json: `"apache`": { `"$($inst.Php.Version.Major).$($inst.Php.Version.Minor)`": `"$($inst.Apache.Name)`" }"
        }
    }

    $map = [ordered]@{}
    foreach ($inst in $started) { foreach ($p in $inst.Projects) { $map[$p.Site.ToLowerInvariant()] = $inst.Ip } }
    Update-Hosts $map $NoHosts

    New-Item -ItemType Directory -Force $Runtime | Out-Null
    [pscustomobject]@{
        startedAt = (Get-Date).ToString('s')
        instances = @($started | ForEach-Object {
            [pscustomobject]@{
                php       = "$($_.Php.Version)"
                apache    = $_.Apache.Name
                ip        = $_.Ip
                pid       = $_.Pid
                projects  = @($_.Projects | ForEach-Object { $_.Name })
                infisical = @($_.Projects | Where-Object { $_.Settings.Infisical } | ForEach-Object { $_.Name })
            }
        })
    } | ConvertTo-Json -Depth 5 | Set-Content $StateFile -Encoding UTF8

    Write-Host ''
    foreach ($inst in $started) {
        Write-Host ('  ✓ PHP {0,-7} {1,-15} {2,-26} PID {3,-6} {4} project(s)' -f $inst.Php.Version, $inst.Ip, $inst.Apache.Name, $inst.Pid, $inst.Projects.Count) -ForegroundColor Green
        foreach ($p in $inst.Projects) {
            if ($p.Settings.Infisical) { Write-Host "      🔑 $($p.Site) ($($p.SecretCount) secret(s))" }
            elseif (-not $inst.IsDefault) { Write-Host "      · $($p.Site)" }
        }
    }
    if ($failed.Count) { Fail "Could not start: PHP $(($failed | ForEach-Object { $_.Php.Version }) -join ', ')" }
}

function Invoke-Status {
    if (-not (Test-Path $StateFile)) { Write-Host 'No instances running (run: dev up)'; return }
    $lg = Get-Laragon
    $state = Get-Content $StateFile -Raw | ConvertFrom-Json
    Write-Host "Started at $($state.startedAt)"
    foreach ($i in @($state.instances)) {
        $alive = [bool](Get-Process -Id $i.pid -ErrorAction SilentlyContinue)
        $health = if ($alive) { Invoke-Health $i.ip $lg.Port } else { $null }
        $mark = if ($health) { 'OK  ' } elseif ($alive) { 'FAIL' } else { 'DOWN' }
        Write-Host ('  {0} PHP {1,-7} {2,-15} {3,-26} PID {4,-6} {5} project(s)' -f $mark, $i.php, $i.ip, $i.apache, $i.pid, @($i.projects).Count)
        if (@($i.infisical).Count) { Write-Host "      🔑 $(@($i.infisical) -join ', ')" }
    }
}

function Invoke-Run([string[]]$Argv) {
    $Argv = @($Argv)
    if ($Argv.Count -ge 2 -and $Argv[1] -eq '--') { $Argv = @($Argv[0]) + @($Argv | Select-Object -Skip 2) }
    if ($Argv.Count -lt 2) { Fail 'Usage: dev run <project> <command...>   e.g. dev run ai-hub php artisan migrate' }
    $lg = Get-Laragon
    $config = Get-Config
    $project = (Get-Projects $lg $config).Projects | Where-Object { $_.Name -ieq $Argv[0] -or $_.Site -ieq $Argv[0] } | Select-Object -First 1
    if (-not $project) { Fail "Project '$($Argv[0])' not found" }
    $settings = Get-ProjectSettings $project $config
    $php = Resolve-PhpBuild $settings.Php @(Get-PhpBuilds $lg) $lg
    $cmd = @($Argv | Select-Object -Skip 1)
    $env:PATH = Get-PathFor $php
    Push-Location $project.Dir
    try {
        if ($settings.Infisical) {
            $a = @('run', '--silent') + @(Get-InfisicalArgs $settings) + @('--') + $cmd
            & (Get-InfisicalExe $config) @a
        } else {
            & $cmd[0] @($cmd | Select-Object -Skip 1)
        }
        $script:ExitCode = $LASTEXITCODE
    } finally {
        Pop-Location
    }
}

function Invoke-SelfTest([string[]]$Specs) {
    $lg = Get-Laragon
    $config = Get-Config
    $phpBuilds = @(Get-PhpBuilds $lg)
    $apacheBuilds = @(Get-ApacheBuilds $lg)
    $defaultPhp = Resolve-PhpBuild $null $phpBuilds $lg
    $targets = if ($Specs.Count) { @($Specs | ForEach-Object { Resolve-PhpBuild $_ $phpBuilds $lg }) } else { $phpBuilds }
    Initialize-HealthFile
    $root = Join-Path $Runtime 'selftest'
    $www = Join-Path $root 'www'
    New-Item -ItemType Directory -Force $www | Out-Null
    $fake = [ordered]@{
        T_PLAIN   = 'hello'
        T_SPECIAL = 'p@ss w0rd $x \y %z ${NOT_EXPANDED} `!&|<>'
        T_QUOTE   = 'he said "hi" \"x\" C:\path\ \\server\'
        T_UNICODE = 'Mật khẩu ✓'
        T_LONG    = 'x' * 10000
    }
    # The fake secrets go through the same JSON parsing as `dev up` (infisical export --format json)
    $json = ConvertTo-Json -Compress -InputObject @($fake.Keys | ForEach-Object { [pscustomobject]@{ key = $_; value = $fake[$_] } })
    $secrets = ConvertFrom-SecretExport ([pscustomobject]@{ Name = 'selftest' }) ([pscustomobject]@{ ExitCode = 0; StdOut = $json; StdErr = '' })
    if ((@($secrets.Keys) -join ',') -ne (@($fake.Keys) -join ',')) {
        Fail "Parsing the JSON of infisical export fails on PowerShell $($PSVersionTable.PSVersion) (keys: $(@($secrets.Keys) -join ', '))"
    }
    $keys = "'" + (@($fake.Keys) -join "','") + "'"
    Write-Utf8File (Join-Path $www 'index.php') @"
<?php
header('Content-Type: application/json');
`$out = [];
foreach ([$keys] as `$k) {
    `$g = getenv(`$k);
    `$out[`$k] = ['getenv' => `$g === false ? null : base64_encode(`$g), 'server' => isset(`$_SERVER[`$k]) ? base64_encode(`$_SERVER[`$k]) : null];
}
`$out['__extensions'] = get_loaded_extensions();
echo json_encode(`$out);
"@
    $wwwA = ConvertTo-ApachePath $www
    $i = 0
    foreach ($php in $targets) {
        $i++
        $preferred = Resolve-Apache $php $config $apacheBuilds $lg
        foreach ($ap in @($preferred) + @($apacheBuilds | Where-Object Name -ne $preferred.Name)) {
            $label = "PHP $($php.Version) + $($ap.Name)"
            $inst = New-Instance $php ($php.Name -eq $defaultPhp.Name) $ap
            $inst.Ip = "127.250.$i.1"
            $inst.Dir = Join-Path $root "$($php.Name)__$($ap.Name)"
            $proj = [pscustomobject]@{
                Name = 'selftest'; Site = 'selftest.invalid'; Source = 'selftest'
                ConfText = "<VirtualHost *:$($lg.Port)>`r`n    ServerName selftest.invalid`r`n    DocumentRoot `"$wwwA`"`r`n    <Directory `"$wwwA`">`r`n        Require all granted`r`n    </Directory>`r`n</VirtualHost>`r`n"
            }
            $b = Build-SecretVars $proj $secrets 'IDEV_SELFTEST__'
            foreach ($k in $b.Vars.Keys) { $inst.EnvVars[$k] = $b.Vars[$k] }
            $proj | Add-Member -NotePropertyName GeneratedConf -NotePropertyValue (New-ProjectConf $proj $b.Lines)
            $inst.Projects.Add($proj)
            Write-InstanceFiles $inst $lg
            $r = Start-Instance $inst $lg
            if (-not $r.Ok) { Write-Host "  ✗ $label — $($r.Error)" -ForegroundColor Red; continue }
            $resp = Invoke-Captured $Curl @('-s', '-m', '5', '--noproxy', '*', '-H', 'Host: selftest.invalid', "http://$($inst.Ip):$($lg.Port)/index.php")
            Stop-ProcessTree $r.Pid
            $bad = @()
            $missing = @()
            $data = $null
            try { $data = ConvertFrom-Json -InputObject $resp.StdOut } catch { }
            if (-not $data) { $bad += "unreadable response: $($resp.StdOut)" }
            else {
                foreach ($k in $fake.Keys) {
                    $expected = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($fake[$k]))
                    if ($data.$k.getenv -ne $expected) { $bad += "$k(getenv)" }
                    if ($data.$k.server -ne $expected) { $bad += "$k(`$_SERVER)" }
                }
                # An extension that loads in the CLI but not in Apache usually means a DLL conflict in Apache's bin\
                $cli = Invoke-Captured (Join-Path $php.Dir 'php.exe') @('-r', 'echo json_encode(get_loaded_extensions());')
                try { $missing = @(ConvertFrom-Json -InputObject ($cli.StdOut.Trim() -split "`n")[-1] | ForEach-Object { $_ } | Where-Object { @($data.__extensions) -notcontains $_ }) }
                catch { $missing = @("? (php.exe -r failed: $($cli.StdErr.Trim()))") }
            }
            $problems = @()
            if ($bad.Count) { $problems += "secrets are wrong: $($bad -join ', ')" }
            if ($missing.Count) { $problems += "extensions missing on the web (they load in the CLI): $($missing -join ', ')" }
            if ($problems.Count) { Write-Host "  ✗ $label — starts, but $($problems -join '; ')" -ForegroundColor Red }
            else { Write-Host "  ✓ $label" -ForegroundColor Green }
            if ($ap.Name -ne $preferred.Name) {
                Write-Warn "Pin it in projects.json: `"apache`": { `"$($php.Version.Major).$($php.Version.Minor)`": `"$($ap.Name)`" }"
            }
            break
        }
    }
    Remove-Item $root -Recurse -Force -ErrorAction SilentlyContinue
}

