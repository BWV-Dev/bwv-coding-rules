function Read-Ini([string]$Path) {
    $ini = @{}
    $section = $null
    foreach ($line in [IO.File]::ReadAllLines($Path)) {
        $t = $line.Trim()
        if ($t -match '^\[(.+)\]$') { $section = $Matches[1]; $ini[$section] = @{}; continue }
        if ($section -and $t -match '^([^=;#]+)=(.*)$') { $ini[$section][$Matches[1].Trim()] = $Matches[2].Trim() }
    }
    $ini
}

function Get-IniValue($Ini, [string]$Section, [string]$Key, $Default = $null) {
    $s = $Ini[$Section]
    if ($s -and $s.ContainsKey($Key) -and $s[$Key] -ne '') { return $s[$Key] }
    $Default
}

function Get-Laragon {
    $iniPath = Join-Path $LaragonRoot 'usr\laragon.ini'
    if (-not (Test-Path $iniPath)) { Fail "$iniPath not found. dev.ps1 must live in <laragon>\usr\dev\" }
    $ini = Read-Ini $iniPath
    $roots = [Collections.Generic.List[string]]::new()
    $candidates = @((Get-IniValue $ini 'preferences' 'DocumentRootList' '') -split '\|') + @(Get-IniValue $ini 'apache' 'DocumentRoot' (Join-Path $LaragonRoot 'www'))
    foreach ($r in $candidates) {
        if (-not $r -or -not $r.Trim()) { continue }
        $n = $r.Trim().TrimEnd('\')
        if ((Test-Path $n -PathType Container) -and -not ($roots | Where-Object { $_ -ieq $n })) { $roots.Add($n) }
    }
    $etc = Join-Path $LaragonRoot 'etc'
    [pscustomobject]@{
        Root          = $LaragonRoot
        ApacheVersion = Get-IniValue $ini 'apache' 'Version'
        PhpVersion    = Get-IniValue $ini 'php' 'Version'
        Port          = [int](Get-IniValue $ini 'apache' 'Port' 80)
        SslEnabled    = (Get-IniValue $ini 'apache' 'SSLEnabled' '0') -eq '-1'
        SslPort       = [int](Get-IniValue $ini 'apache' 'SSLPort' 443)
        WwwRoots      = $roots.ToArray()
        SitesDir      = Join-Path $etc 'apache2\sites-enabled'
        SslConf       = Join-Path $etc 'apache2\httpd-ssl.conf'
        TplFile       = Join-Path $LaragonRoot 'usr\tpl\VirtualHost.tpl'
        SslCrt        = Join-Path $etc 'ssl\laragon.crt'
        SslKey        = Join-Path $etc 'ssl\laragon.key'
    }
}

# Only Thread Safe x64 builds that ship php*apache2_4.dll (mod_php cannot load NTS/x86 builds).
function Get-PhpBuilds($Lg) {
    $result = @()
    foreach ($d in Get-ChildItem (Join-Path $Lg.Root 'bin\php') -Directory) {
        $m = [regex]::Match($d.Name, '^php-(\d+)\.(\d+)\.(\d+)')
        if (-not $m.Success -or $d.Name -match '-nts-' -or $d.Name -notmatch 'x64') { continue }
        $dll = Get-ChildItem $d.FullName -Filter 'php*apache2_4.dll' -File | Select-Object -First 1
        if (-not $dll) { continue }
        $module = switch ($dll.Name) { 'php7apache2_4.dll' { 'php7_module' } 'php5apache2_4.dll' { 'php5_module' } default { 'php_module' } }
        $result += [pscustomobject]@{
            Name    = $d.Name
            Dir     = $d.FullName
            Dll     = $dll.FullName
            Module  = $module
            Version = [version]"$($m.Groups[1].Value).$($m.Groups[2].Value).$($m.Groups[3].Value)"
        }
    }
    $result
}

function Resolve-PhpBuild($Spec, $Builds, $Lg) {
    if (-not $Spec) {
        $b = $Builds | Where-Object Name -eq $Lg.PhpVersion | Select-Object -First 1
        if (-not $b) { Fail "Laragon's default PHP ($($Lg.PhpVersion)) is not a Thread Safe x64 build with php*apache2_4.dll" }
        return $b
    }
    $Spec = [string]$Spec
    $b = $Builds | Where-Object { $_.Name -eq $Spec -or "$($_.Version)" -eq $Spec -or "$($_.Version)".StartsWith("$Spec.") } |
        Sort-Object Version -Descending | Select-Object -First 1
    if (-not $b) { Fail "PHP '$Spec' (Thread Safe x64) not found. Available: $(($Builds | ForEach-Object { $_.Version }) -join ', ')" }
    $b
}

function Get-ApacheBuilds($Lg) {
    Get-ChildItem (Join-Path $Lg.Root 'bin\apache') -Directory |
        Where-Object { (Test-Path (Join-Path $_.FullName 'bin\httpd.exe')) -and (Test-Path (Join-Path $_.FullName 'conf\httpd.conf')) } |
        ForEach-Object { [pscustomobject]@{ Name = $_.Name; Dir = $_.FullName } }
}

# Laragon copies its default PHP's DLLs (php8ts.dll, libsqlite3.dll, libssh2.dll...) into Apache's bin\, and Windows
# loads DLLs from the httpd.exe folder first. An instance on another PHP version therefore runs httpd from its own bin\
# of hard links, where each DLL that the instance's PHP also ships is replaced by the PHP's own copy.
function Get-InstanceBin($Inst) {
    $bin = Join-Path $Inst.Apache.Dir 'bin'
    if ($Inst.IsDefault) { return $bin }
    $swap = @{}
    foreach ($f in Get-ChildItem $bin -File -Filter '*.dll') {
        $own = Join-Path $Inst.Php.Dir $f.Name
        if ((Test-Path $own) -and (Get-FileHash $own).Hash -ne (Get-FileHash $f.FullName).Hash) { $swap[$f.Name] = $own }
    }
    if (-not $swap.Count) { return $bin }
    $private = Join-Path $Inst.Dir 'bin'
    try { if (Test-Path $private) { Remove-Item $private -Recurse -Force -ErrorAction Stop } }
    catch { Fail "Cannot refresh $private (is an old httpd still running? Run: dev down)" }
    foreach ($f in Get-ChildItem $bin -File -Recurse) {
        $target = Join-Path $private $f.FullName.Substring($bin.Length + 1)
        New-Item -ItemType Directory -Force (Split-Path $target -Parent) | Out-Null
        $source = if ($f.DirectoryName -eq $bin -and $swap.ContainsKey($f.Name)) { $swap[$f.Name] } else { $f.FullName }
        # Hard links need the same NTFS volume; copy otherwise
        try { New-Item -ItemType HardLink -Path $target -Value $source -ErrorAction Stop | Out-Null }
        catch { Copy-Item $source $target }
    }
    $private
}

function Resolve-Apache($Php, $Config, $ApacheBuilds, $Lg) {
    $map = Get-Prop $Config 'apache'
    $name = $null
    foreach ($k in @($Php.Name, "$($Php.Version)", "$($Php.Version.Major).$($Php.Version.Minor)")) {
        $v = Get-Prop $map $k
        if ($v) { $name = $v; break }
    }
    if (-not $name) { $name = $Lg.ApacheVersion }
    $a = $ApacheBuilds | Where-Object Name -eq $name | Select-Object -First 1
    if (-not $a) { Fail "Apache '$name' not found in bin\apache" }
    $a
}

