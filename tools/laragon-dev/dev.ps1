# Laragon's default PHP uses 127.0.0.1 (Laragon's hosts entries stay valid); other versions get 127.<major><minor>.<patch>.1
function New-Instance($Php, [bool]$IsDefault, $Apache) {
    $ip = if ($IsDefault) { $DefaultIp } else { "127.$($Php.Version.Major * 10 + $Php.Version.Minor).$($Php.Version.Build).1" }
    [pscustomobject]@{
        Name       = $Php.Name
        Php        = $Php
        Apache     = $Apache
        IsDefault  = $IsDefault
        Ip         = $ip
        Dir        = Join-Path $Runtime "instances\$($Php.Name)"
        Projects   = [Collections.Generic.List[object]]::new()
        EnvVars    = [ordered]@{}
        ExtraConfs = @()
        Pid        = $null
    }
}

function New-ProjectConf($Project, [string[]]$SecretLines) {
    $text = $Project.ConfText
    if ($SecretLines -and $SecretLines.Count) {
        $inject = ($SecretLines -join "`r`n") + "`r`n"
        $text = [regex]::Replace($text, '(?im)^([ \t]*</VirtualHost>)', $inject.Replace('$', '$$') + '$1')
    }
    "# Generated by dev.ps1 from the Laragon vhost ($($Project.Source)); do not edit`r`n" + $text
}

# Take the httpd.conf Laragon uses for that Apache build, drop Laragon's Listen/vhosts/mod_php, add the instance's part.
function New-InstanceConf($Inst, $Lg) {
    $dir = ConvertTo-ApachePath $Inst.Dir
    $health = ConvertTo-ApachePath (Join-Path $Runtime 'health')
    $out = [Collections.Generic.List[string]]::new()
    $out.Add("# Generated by dev.ps1 from Laragon's $($Inst.Apache.Name)\conf\httpd.conf; do not edit")
    foreach ($line in [IO.File]::ReadAllLines((Join-Path $Inst.Apache.Dir 'conf\httpd.conf'))) {
        if ($line -match '^\s*(Listen|PidFile)\s') { continue }
        if ($line -match '^\s*Include(Optional)?\s.*(sites-enabled|httpd-ssl\.conf|mod_php\.conf)') { continue }
        if ($line -match '^\s*ErrorLog\s') { $out.Add("ErrorLog `"$dir/logs/error.log`""); continue }
        if ($line -match '^\s*CustomLog\s') { $out.Add("    CustomLog `"$dir/logs/access.log`" common"); continue }
        $out.Add($line)
    }
    $port = $Lg.Port
    $out.Add(@"

# ---- dev.ps1: instance PHP $($Inst.Php.Version) ----
PidFile "$dir/httpd.pid"
DefaultRuntimeDir "$dir/run"
Listen $($Inst.Ip):$port
LoadModule $($Inst.Php.Module) "$(ConvertTo-ApachePath $Inst.Php.Dll)"
PHPIniDir "$(ConvertTo-ApachePath $Inst.Php.Dir)"
<IfModule mime_module>
    AddType application/x-httpd-php .php
</IfModule>

<Directory "$health">
    Require all granted
</Directory>
<VirtualHost _default_:$port>
    Alias /__dev/health "$health/index.php"
</VirtualHost>
"@)
    if ($Lg.SslEnabled -and (Test-Path $Lg.SslConf)) {
        $out.Add("Listen $($Inst.Ip):$($Lg.SslPort)")
        foreach ($line in [IO.File]::ReadAllLines($Lg.SslConf)) {
            if ($line -match '^\s*Listen\s') { continue }
            if ($line -match '^\s*SSLSessionCache\s') { $out.Add("SSLSessionCache `"shmcb:$dir/run/ssl_scache(512000)`""); continue }
            $out.Add($line)
        }
        $out.Add(@"
<VirtualHost _default_:$($Lg.SslPort)>
    SSLEngine on
    SSLCertificateFile    "$(ConvertTo-ApachePath $Lg.SslCrt)"
    SSLCertificateKeyFile "$(ConvertTo-ApachePath $Lg.SslKey)"
    Alias /__dev/health "$health/index.php"
</VirtualHost>
"@)
    }
    # Project vhosts first: Apache serves a domain from the first vhost that names it, so an extra vhost for the
    # same domain must not shadow the one with the secrets
    $out.Add("IncludeOptional `"$dir/sites/*.conf`"")
    foreach ($f in $Inst.ExtraConfs) { $out.Add("IncludeOptional `"$(ConvertTo-ApachePath $f)`"") }
    $out -join "`r`n"
}

function Write-InstanceFiles($Inst, $Lg) {
    $sites = Join-Path $Inst.Dir 'sites'
    foreach ($d in @($sites, (Join-Path $Inst.Dir 'logs'), (Join-Path $Inst.Dir 'run'))) { New-Item -ItemType Directory -Force $d | Out-Null }
    Get-ChildItem $sites -Filter '*.conf' -File | Remove-Item -Force
    foreach ($p in $Inst.Projects) { Write-Utf8File (Join-Path $sites "$($p.Site).conf") $p.GeneratedConf }
    Write-Utf8File (Join-Path $Inst.Dir 'httpd.conf') (New-InstanceConf $Inst $Lg)
}

function Initialize-HealthFile {
    $dir = Join-Path $Runtime 'health'
    New-Item -ItemType Directory -Force $dir | Out-Null
    Write-Utf8File (Join-Path $dir 'index.php') "<?php header('Content-Type: text/plain'); echo PHP_VERSION;"
}

function Invoke-Health([string]$Ip, [int]$Port) {
    $r = Invoke-Captured $Curl @('-s', '-m', '3', '--noproxy', '*', '-H', 'Host: dev-health.invalid', "http://${Ip}:$Port/__dev/health")
    if ($r.ExitCode -eq 0 -and $r.StdOut -match '^\d+\.\d+\.\d+') { return $r.StdOut.Trim() }
    $null
}

# Secrets are put into the current process env only while httpd is being spawned, then removed right away.
function Start-Instance($Inst, $Lg) {
    $conf = Join-Path $Inst.Dir 'httpd.conf'
    $httpd = Join-Path (Get-InstanceBin $Inst) 'httpd.exe'
    $serverRoot = ConvertTo-ApachePath $Inst.Apache.Dir
    $savedPath = $env:PATH
    $proc = $null
    try {
        $env:PATH = Get-PathFor $Inst.Php
        foreach ($k in $Inst.EnvVars.Keys) { [Environment]::SetEnvironmentVariable($k, $Inst.EnvVars[$k], 'Process') }
        # -d: httpd may run from the instance's own bin\, so ServerRoot cannot be derived from its folder
        $test = Invoke-Captured $httpd @('-t', '-d', $serverRoot, '-f', $conf)
        if ($test.ExitCode -ne 0) { return [pscustomobject]@{ Ok = $false; Error = ($test.StdErr + $test.StdOut).Trim() } }
        $proc = Start-Process -FilePath $httpd -ArgumentList @('-d', "`"$serverRoot`"", '-f', "`"$conf`"") -WindowStyle Hidden -PassThru
    } finally {
        foreach ($k in $Inst.EnvVars.Keys) { [Environment]::SetEnvironmentVariable($k, $null, 'Process') }
        $env:PATH = $savedPath
    }
    $deadline = (Get-Date).AddSeconds(20)
    while ((Get-Date) -lt $deadline) {
        Start-Sleep -Milliseconds 400
        if ($proc.HasExited) { break }
        $body = Invoke-Health $Inst.Ip $Lg.Port
        if ($body) { return [pscustomobject]@{ Ok = $true; Pid = $proc.Id; Body = $body } }
    }
    if (-not $proc.HasExited) { Stop-ProcessTree $proc.Id }
    $log = Join-Path $Inst.Dir 'logs\error.log'
    $tail = if (Test-Path $log) { ((Get-Content $log -Tail 3) -join ' | ') } else { '' }
    [pscustomobject]@{ Ok = $false; Error = "health check failed (PHP cannot run on this Apache build?) $tail".Trim() }
}

function Stop-All([switch]$Quiet) {
    $pids = @()
    if (Test-Path $StateFile) { $pids += @((Get-Content $StateFile -Raw | ConvertFrom-Json).instances | ForEach-Object { $_.pid }) }
    $pidFiles = @(Get-ChildItem (Join-Path $Runtime '*\*\httpd.pid') -ErrorAction SilentlyContinue)
    foreach ($f in $pidFiles) { $pids += [int]([IO.File]::ReadAllText($f.FullName).Trim()) }
    $stopped = 0
    foreach ($id in @($pids | Where-Object { $_ } | Sort-Object -Unique)) {
        $proc = Get-Process -Id $id -ErrorAction SilentlyContinue
        if ($proc -and $proc.ProcessName -eq 'httpd') { Stop-ProcessTree $id; $stopped++ }
    }
    $pidFiles | Remove-Item -Force -ErrorAction SilentlyContinue
    Remove-Item $StateFile -Force -ErrorAction SilentlyContinue
    if (-not $Quiet) { Write-Step "Stopped $stopped instance(s)" }
}

# Every site shares laragon.crt; domains Laragon hasn't added to the cert get an invalid-certificate error over HTTPS.
function Write-CertWarning($Projects, $Lg) {
    if (-not $Lg.SslEnabled -or -not (Test-Path $Lg.SslCrt)) { return }
    $cert = [Security.Cryptography.X509Certificates.X509Certificate2]::new($Lg.SslCrt)
    $ext = $cert.Extensions | Where-Object { $_.Oid.Value -eq '2.5.29.17' } | Select-Object -First 1
    $names = if ($ext) { @($ext.Format($false) -split ',\s*' | ForEach-Object { ($_ -split '[=:]', 2)[1] }) } else { @() }
    $missing = @($Projects | Where-Object { $names -notcontains $_.Site.ToLowerInvariant() } | ForEach-Object { $_.Site })
    if ($missing.Count) {
        Write-Warn "laragon.crt does not cover: $($missing -join ', '). HTTPS for these sites will show an invalid certificate (HTTP still works). To let Laragon regenerate the cert: dev down → start Apache in Laragon once → stop it → dev up."
    }
}

function Assert-PortsFree($Instances, $Lg) {
    $ports = @($Lg.Port)
    if ($Lg.SslEnabled) { $ports += $Lg.SslPort }
    try { $listen = @(Get-NetTCPConnection -State Listen -ErrorAction Stop | Where-Object { $ports -contains $_.LocalPort }) }
    catch { Write-Warn 'Could not check ports (Get-NetTCPConnection)'; return }
    $problems = @()
    foreach ($inst in $Instances) {
        foreach ($c in $listen) {
            if ($c.LocalAddress -ne '0.0.0.0' -and $c.LocalAddress -ne $inst.Ip) { continue }
            $proc = Get-Process -Id $c.OwningProcess -ErrorAction SilentlyContinue
            $problems += "    $($c.LocalAddress):$($c.LocalPort) ← $($proc.ProcessName) (PID $($c.OwningProcess)) $($proc.Path)"
        }
    }
    $problems = @($problems | Sort-Object -Unique)
    if ($problems.Count) {
        Fail ("Port already in use:`n" + ($problems -join "`n") +
            "`n  → If it is Laragon's Apache: stop Apache in Laragon and uncheck Apache in Preferences > Services & Ports so 'Start All' doesn't start it again.")
    }
}

