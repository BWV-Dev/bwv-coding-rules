<#
  dev.ps1 — run Laragon projects on Apache + mod_php with secrets from Infisical.
  Secret values live only in the memory of the Apache processes; generated config files
  contain variable names (${...}) only.

  Commands:
    dev up [--no-hosts]         Stop old instances, generate config, load secrets, start, update hosts
    dev restart                 Same as dev up
    dev down                    Stop all instances
    dev status                  Show instance status
    dev run <project> <cmd>     Run a command with the project's PHP + secrets (e.g. dev run ai-hub php artisan migrate)
    dev selftest [php ...]      Check PHP/Apache pairs and secret passing using fake secrets
    dev hosts-reset             Remove the hosts entries managed by dev.ps1 and restore Laragon's lines

  Read from Laragon:
    usr\laragon.ini              www folders, Apache build, default PHP, ports, SSL
    etc\apache2\sites-enabled\   domain + DocumentRoot (auto.*.conf vhosts generated by Laragon)
    usr\tpl\VirtualHost.tpl      vhost for folders Laragon has not generated a vhost for yet
    bin\apache\*\conf\httpd.conf Apache modules and settings
    etc\apache2\httpd-ssl.conf, etc\ssl\laragon.crt
  Read from each project:
    .infisical.yaml              (created by `infisical init`; legacy .infisical.json) — if present, the project uses Infisical

  projects.json only declares what Laragon does not know:
    {
      "apache":   { "8.2": "httpd-2.4.54-win64-VS16" },      // pin an Apache build for a PHP version
      "projects": {
        "bwv-tools": { "php": "7.2" },                        // default: the PHP selected in Laragon
        "ai-hub":    { "php": "8.2", "env": "dev", "path": "/" },
        "legacy":    { "projectId": "xxx" },                  // use Infisical without .infisical.yaml
        "abc":       { "infisical": false }                   // disable Infisical for this project
      },
      "hostnameTemplate": "{name}.test",
      "infisicalPath": "C:\\path\\to\\infisical.exe"
    }
#>
