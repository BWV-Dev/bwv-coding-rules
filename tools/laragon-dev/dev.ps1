function ConvertTo-ArgString([string[]]$Items) {
    ($Items | ForEach-Object {
        if ($_ -eq '') { '""' } elseif ($_ -match '[\s"]') { '"' + ($_ -replace '"', '\"') + '"' } else { $_ }
    }) -join ' '
}

# Start a process and read stdout/stderr into memory (never through a file). The child inherits the current env.
function Start-Captured([string]$Exe, [string[]]$Arguments, [string]$WorkDir = $DevDir) {
    $psi = [Diagnostics.ProcessStartInfo]::new()
    if ($Exe -match '\.(cmd|bat)$') {
        $psi.FileName = $env:ComSpec
        $psi.Arguments = '/d /s /c "' + (ConvertTo-ArgString (@($Exe) + $Arguments)) + '"'
    } else {
        $psi.FileName = $Exe
        $psi.Arguments = ConvertTo-ArgString $Arguments
    }
    $psi.WorkingDirectory = $WorkDir
    $psi.UseShellExecute = $false
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true
    $psi.StandardOutputEncoding = [Text.Encoding]::UTF8
    $psi.StandardErrorEncoding = [Text.Encoding]::UTF8
    $proc = [Diagnostics.Process]::Start($psi)
    [pscustomobject]@{ Process = $proc; Out = $proc.StandardOutput.ReadToEndAsync(); Err = $proc.StandardError.ReadToEndAsync() }
}

function Wait-Captured($Handle) {
    $Handle.Process.WaitForExit()
    [pscustomobject]@{ ExitCode = $Handle.Process.ExitCode; StdOut = $Handle.Out.Result; StdErr = $Handle.Err.Result }
}

function Invoke-Captured([string]$Exe, [string[]]$Arguments, [string]$WorkDir = $DevDir) {
    Wait-Captured (Start-Captured $Exe $Arguments $WorkDir)
}

function Stop-ProcessTree([int]$ProcessId) {
    Invoke-Captured (Join-Path $env:SystemRoot 'System32\taskkill.exe') @('/T', '/F', '/PID', "$ProcessId") | Out-Null
}

