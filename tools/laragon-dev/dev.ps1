function ConvertTo-Lf([string]$Text) { ($Text -replace "\r\n", "`n").TrimEnd() }

# Drop the old dev.ps1 block and re-enable lines it disabled; then disable lines pointing to the wrong IP
# and put a new block at the top of the file.
function Get-DesiredHosts([string]$Current, $Mappings) {
    $lines = [Collections.Generic.List[string]]::new()
    $inBlock = $false
    foreach ($l in ($Current -split "\r?\n")) {
        if ($l -eq $HostsBegin) { $inBlock = $true; continue }
        if ($l -eq $HostsEnd) { $inBlock = $false; continue }
        if ($inBlock) { continue }
        if ($l.StartsWith($HostsOffTag)) { $l = $l.Substring($HostsOffTag.Length) }
        $lines.Add($l)
    }
    $block = @()
    if ($Mappings) {
        $satisfied = @{}
        for ($i = 0; $i -lt $lines.Count; $i++) {
            $m = [regex]::Match($lines[$i], '^\s*(\d{1,3}(?:\.\d{1,3}){3})\s+([^\s#]+)')
            if (-not $m.Success) { continue }
            $hostName = $m.Groups[2].Value.ToLowerInvariant()
            if (-not $Mappings.Contains($hostName)) { continue }
            if ($m.Groups[1].Value -eq $Mappings[$hostName]) { $satisfied[$hostName] = $true }
            else { $lines[$i] = $HostsOffTag + $lines[$i] }
        }
        foreach ($h in $Mappings.Keys) {
            if (-not $satisfied.ContainsKey($h)) { $block += ('{0,-15} {1}' -f $Mappings[$h], $h) }
        }
    }
    $body = ($lines -join "`r`n").TrimEnd("`r", "`n")
    if ($block.Count) { $body = ((@($HostsBegin) + $block + @($HostsEnd)) -join "`r`n") + "`r`n" + $body }
    $body + "`r`n"
}

function Write-HostsFile([string]$Content) {
    New-Item -ItemType Directory -Force $Runtime | Out-Null
    Copy-Item $HostsFile (Join-Path $Runtime 'hosts.bak') -Force
    [IO.File]::WriteAllText($HostsFile, $Content, [Text.UTF8Encoding]::new($false))
    ipconfig /flushdns | Out-Null
}

function Set-HostsContent([string]$Content) {
    if (Test-Admin) { Write-HostsFile $Content; return }
    New-Item -ItemType Directory -Force $Runtime | Out-Null
    $tmp = Join-Path $Runtime 'hosts.pending'
    Write-Utf8File $tmp $Content
    Write-Step 'Admin rights are needed to edit hosts (UAC)...'
    try {
        $exe = (Get-Process -Id $PID).Path
        Start-Process -FilePath $exe -Verb RunAs -Wait -WindowStyle Hidden -ArgumentList @(
            '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', "`"$PSCommandPath`"", '_write-hosts', "`"$tmp`"")
    } catch {
        Fail 'Could not edit hosts (UAC declined?)'
    } finally {
        Remove-Item $tmp -Force -ErrorAction SilentlyContinue
    }
    if ((ConvertTo-Lf ([IO.File]::ReadAllText($HostsFile))) -ne (ConvertTo-Lf $Content)) { Write-Warn 'hosts was not updated as expected' }
}

function Update-Hosts($Mappings, [bool]$Skip) {
    $current = [IO.File]::ReadAllText($HostsFile)
    $desired = Get-DesiredHosts $current $Mappings
    if ((ConvertTo-Lf $current) -eq (ConvertTo-Lf $desired)) { return }
    if ($Skip) { Write-Warn 'hosts needs an update but it was skipped (--no-hosts)'; return }
    Set-HostsContent $desired
    Write-Step 'hosts updated'
}

